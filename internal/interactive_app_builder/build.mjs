/**
 * Builds the interactive simulations into the tutorial project:
 *
 *   runtime/            →  tutorial/webContent/resources/js/interactive-runtime.min.js
 *   features/<name>/    →  tutorial/webContent/resources/js/<name>.js      (e.g. feature-01.js)
 *
 * Everything a browser needs — three.js included — ends up in those files, so the Feature
 * Guide works without a network connection.
 *
 *   node build.mjs            build
 *   node build.mjs --watch    rebuild on change
 *   node build.mjs --check    fail if the committed files are not what the sources produce
 */
import { build, context, transform } from 'esbuild';
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const repo = resolve(root, '../..');
const outDir = join(repo, 'tutorial/webContent/resources/js');
const RUNTIME_FILE = 'interactive-runtime.min.js';

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const three = JSON.parse(readFileSync(join(root, 'node_modules/three/package.json'), 'utf8'));
const threeLicense = readFileSync(join(root, 'node_modules/three/LICENSE'), 'utf8').trim().replace(/©/g, '(c)');

const args = new Set(process.argv.slice(2));

/** Feature folders: features/<name>/index.js → <name>.js */
function featureNames() {
  const dir = join(root, 'features');
  return readdirSync(dir).filter(name => statSync(join(dir, name)).isDirectory() && existsSync(join(dir, name, 'index.js'))).sort();
}

/** Stylesheets are imported as (minified) text and injected into the shadow root. */
const cssAsText = {
  name: 'css-as-text',
  setup(b) {
    b.onLoad({ filter: /\.css$/ }, async file => {
      const result = await transform(await readFile(file.path, 'utf8'), { loader: 'css', minify: true });
      return { contents: result.code, loader: 'text' };
    });
  }
};

const shared = {
  bundle: true,
  format: 'iife',
  target: ['es2019'],
  minify: true,
  charset: 'ascii', // no encoding surprises, however the file is served
  legalComments: 'none', // the three.js notice is part of the banner below
  // source files of the tutorial project that a lesson shows: imported as text
  loader: { '.java': 'text', '.SmartWorkflowToolsProvider': 'text' },
  logLevel: 'warning'
};

const generated = ' * Generated by internal/interactive_app_builder (npm run build) - do not edit.';

function runtimeOptions() {
  return {
    ...shared,
    entryPoints: [join(root, 'runtime/index.js')],
    outfile: join(outDir, RUNTIME_FILE),
    plugins: [cssAsText],
    define: { __SW_VERSION__: JSON.stringify(pkg.version) },
    banner: {
      js: '/*!\n * Smart Workflow tutorial - interactive simulation runtime ' + pkg.version + '\n' + generated + '\n *\n' +
        ' * Bundles three.js ' + three.version + ' (https://threejs.org):\n *\n' +
        threeLicense.split(/\r?\n/).map(line => (' * ' + line).trimEnd()).join('\n') + '\n */'
    }
  };
}

function featureOptions(name) {
  const dir = join(root, 'features', name);
  return {
    ...shared,
    stdin: {
      // Works whether this script loads before or after the runtime.
      contents: "import definition from './index.js';\n" +
        'if (window.swInteractive) window.swInteractive.register(definition.id, definition);\n' +
        'else (window.__swInteractiveQueue = window.__swInteractiveQueue || []).push([definition.id, definition]);\n',
      resolveDir: dir,
      sourcefile: 'register-' + name + '.js'
    },
    outfile: join(outDir, name + '.js'),
    banner: { js: '/*!\n * Smart Workflow tutorial - interactive simulation: ' + name + '\n' + generated + '\n * Source: internal/interactive_app_builder/features/' + name + '/\n */' }
  };
}

function inspect(file, text) {
  const problems = [];
  // JSF evaluates #{...} in some resources; make sure a bundle can never contain it.
  if (text.includes('#{')) problems.push('contains "#{", which JSF may treat as an expression');
  if (/[^\x00-\x7f]/.test(text)) problems.push('contains non-ASCII characters');
  if (problems.length) throw new Error(relative(repo, file) + ': ' + problems.join('; '));
}

const kb = bytes => (bytes / 1024).toFixed(1).padStart(7) + ' kB';

async function buildAll({ write }) {
  const jobs = [runtimeOptions(), ...featureNames().map(featureOptions)];
  const outputs = [];
  for (const options of jobs) {
    const result = await build({ ...options, write: false });
    // esbuild escapes non-ASCII text everywhere except inside regular expression literals
    // (e.g. /請求書番号/ in a feature's rules); escape what is left so the files are pure ASCII.
    const text = result.outputFiles[0].text.replace(/[^\x00-\x7f]/g, c => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
    inspect(result.outputFiles[0].path, text);
    outputs.push({ path: result.outputFiles[0].path, text });
  }
  if (write) {
    mkdirSync(outDir, { recursive: true });
    outputs.forEach(out => writeFileSync(out.path, out.text));
  }
  return outputs;
}

if (args.has('--watch')) {
  const contexts = await Promise.all([runtimeOptions(), ...featureNames().map(featureOptions)].map(o => context({ ...o, logLevel: 'info' })));
  await Promise.all(contexts.map(c => c.watch()));
  console.log('Watching for changes. Output: ' + relative(repo, outDir));
} else if (args.has('--check')) {
  const outputs = await buildAll({ write: false });
  const stale = outputs.filter(out => !existsSync(out.path) || readFileSync(out.path, 'utf8') !== out.text);
  if (stale.length) {
    console.error('Out of date - run "npm run build":');
    stale.forEach(out => console.error('  ' + relative(repo, out.path)));
    process.exit(1);
  }
  console.log('Up to date: ' + outputs.map(o => relative(outDir, o.path)).join(', '));
} else {
  const outputs = await buildAll({ write: true });
  console.log('Built into ' + relative(repo, outDir) + ':');
  outputs.forEach(out => console.log('  ' + kb(Buffer.byteLength(out.text)) + '  ' + relative(outDir, out.path)));
}
