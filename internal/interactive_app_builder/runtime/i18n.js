/** The Feature Guide calls Japanese "jp"; everything else falls back to English. */
export function normalizeLanguage(lang) {
  const l = String(lang || 'en').toLowerCase();
  return l === 'jp' || l.startsWith('ja') ? 'ja' : 'en';
}

/**
 * @param {string} lang
 * @param {{en?:Object, ja?:Object}} [featureStrings]  looked up before the runtime's own
 * @returns {(key: string, params?: Object) => string}
 */
export function createTranslator(lang, featureStrings = {}) {
  const language = normalizeLanguage(lang);
  const sources = [featureStrings[language], STRINGS[language], featureStrings.en, STRINGS.en].filter(Boolean);
  return (key, params) => {
    let text = key;
    for (const source of sources) {
      if (source[key] !== undefined) { text = source[key]; break; }
    }
    if (!params) return text;
    return String(text).replace(/\{(\w+)\}/g, (m, name) => (params[name] === undefined ? m : params[name]));
  };
}
